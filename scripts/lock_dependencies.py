#!/usr/bin/env python3
"""Generate or check complete, hashed dependency locks without installing packages."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UV_VERSION = "0.9.10"
PROFILES = ("runtime", "dev")


def source_inputs(root: Path, profile: str) -> tuple[str, str]:
    project = tomllib.loads((root / "pyproject.toml").read_text())
    if project["tool"]["setuptools"]["dynamic"]["dependencies"] != {"file": ["requirements.txt"]}:
        raise ValueError("Application dependencies must come from requirements.txt.")
    requirements = (root / "requirements.txt").read_text()
    build = project["build-system"]["requires"]
    optional = project["project"]["optional-dependencies"]
    extras = list(dict.fromkeys(optional["test"] + optional["dev"])) if profile == "dev" else []
    sources = {
        "requirements": requirements,
        "build": build,
        "extras": extras,
        "requires-python": project["project"]["requires-python"],
        "uv": UV_VERSION,
    }
    digest = hashlib.sha256(json.dumps(sources, sort_keys=True).encode()).hexdigest()
    return requirements + "\n" + "\n".join(build + extras) + "\n", digest


def check_lock(root: Path, profile: str) -> None:
    _, digest = source_inputs(root, profile)
    path = root / "requirements" / f"{profile}.lock"
    content = path.read_text()
    if f"# source-input-sha256: {digest}\n" not in content:
        raise ValueError(f"{path.name} is stale; run python scripts/lock_dependencies.py --generate.")
    entries = [line.strip() for line in content.replace("\\\n", " ").splitlines() if line.strip() and not line.startswith("#")]
    if not entries or any(
        not re.fullmatch(r"[a-z0-9-]+(?:\[[a-z0-9,._-]+\])?==[^\s;]+(?:\s*;[^\\]+?)?\s+(?:--hash=sha256:[a-f0-9]{64}\s*)+", entry)
        for entry in entries
    ):
        raise ValueError(f"{path.name} must contain only exact versions and SHA-256 hashes.")


def generate_locks(root: Path, upgrades: list[str]) -> None:
    version = subprocess.check_output(["uv", "--version"], text=True).split()[1]
    if version != UV_VERSION:
        raise ValueError(f"Regenerate using uv {UV_VERSION}; found {version}.")
    project = tomllib.loads((root / "pyproject.toml").read_text())
    if project["project"]["requires-python"] != ">=3.11":
        raise ValueError("Update the lock generator's Python floor when changing requires-python.")
    with tempfile.TemporaryDirectory(prefix="gromacs-dependency-lock-") as directory:
        work = Path(directory)
        for profile in PROFILES:
            sources, digest = source_inputs(root, profile)
            source = work / f"{profile}.in"
            source.write_text(sources)
            destination = root / "requirements" / f"{profile}.lock"
            output = work / destination.name
            if destination.exists():
                # uv prefers existing pins; updating a source does not upgrade everything.
                output.write_bytes(destination.read_bytes())
            command = [
                "uv",
                "pip",
                "compile",
                str(source),
                "--universal",
                "--python-version",
                "3.11",
                "--generate-hashes",
                "--no-annotate",
                "--no-header",
                "--no-strip-extras",
                "--output-file",
                str(output),
                "--quiet",
            ]
            if profile == "dev":
                command.extend(["--constraint", str(work / "runtime.lock")])
            for package in upgrades:
                command.extend(["--upgrade-package", package])
            subprocess.run(command, check=True, timeout=1800)
            header = (
                "# Generated by python scripts/lock_dependencies.py --generate; do not edit.\n"
                "# Python >=3.11; platform/Python markers select compatible dependencies.\n"
                f"# source-input-sha256: {digest}\n\n"
            )
            output.write_text(header + output.read_text())
        # Write only after both resolutions succeed.
        (root / "requirements").mkdir(exist_ok=True)
        for profile in PROFILES:
            (root / "requirements" / f"{profile}.lock").write_bytes((work / f"{profile}.lock").read_bytes())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--generate", action="store_true")
    action.add_argument("--check", action="store_true")
    parser.add_argument(
        "--upgrade-package", action="append", default=[], help="Deliberately update one package while preserving other pins."
    )
    args = parser.parse_args()
    if args.upgrade_package and not args.generate:
        parser.error("--upgrade-package requires --generate")
    if args.generate:
        generate_locks(ROOT, args.upgrade_package)
    for profile in PROFILES:
        check_lock(ROOT, profile)
    print("Dependency locks match their source requirements.")


if __name__ == "__main__":
    main()
